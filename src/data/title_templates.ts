// ── 동(읍면동) 페이지 제목 (2,000가지) — r = "시군구 동이름" ───────────────
export const DONG_TITLES: ((r: string) => string)[] = (() => {
  const arr: ((r: string) => string)[] = [];
  TARGETS.forEach(target => {
    SOLUTIONS.forEach(solution => {
      SUFFIXES.forEach(suffix => {
        // 기존 | 제거 및 자연스러운 띄어쓰기로 변경
        arr.push((r: string) => `${r} ${target} ${solution} ${suffix}`);
      });
    });
  });
  return arr;
})();

// ── 동(읍면동) 페이지 설명 (2,000가지) ─────────────────────────────────────
export const DONG_DESCS: ((r: string) => string)[] = (() => {
  const arr: ((r: string) => string)[] = [];
  DONG_INTRO.forEach(intro => {
    DESC_BODY.forEach(body => {
      DESC_OUTRO.forEach(outro => {
        arr.push((r: string) => `${intro.replace(/\{r\}/g, r)} ${body} ${outro}`);
      });
    });
  });
  return arr;
})();

// ── 시군구 허브 페이지 제목 (2,000가지) — sg=시군구, sd=시도 ───────────────
export const SIGUNGU_TITLES: ((sg: string, sd: string) => string)[] = (() => {
  const arr: ((sg: string, sd: string) => string)[] = [];
  TARGETS.forEach(target => {
    SOLUTIONS.forEach(solution => {
      SUFFIXES.forEach(suffix => {
        // 기존 | 제거 및 자연스러운 띄어쓰기로 변경
        arr.push((sg: string, sd: string) => `${sg} ${target} ${solution} ${sd} ${suffix}`);
      });
    });
  });
  return arr;
})();

// ── 시군구 허브 페이지 설명 (2,000가지) ─────────────────────────────────────
export const SIGUNGU_DESCS: ((sg: string, sd: string) => string)[] = (() => {
  const arr: ((sg: string, sd: string) => string)[] = [];
  SIGUNGU_INTRO.forEach(intro => {
    DESC_BODY.forEach(body => {
      DESC_OUTRO.forEach(outro => {
        arr.push((sg: string, sd: string) => {
          let mergedIntro = intro.replace(/\{sg\}/g, sg).replace(/\{sd\}/g, sd);
          return `${mergedIntro} ${body} ${outro}`;
        });
      });
    });
  });
  return arr;
})();

// ── 씨드 계산 헬퍼 (지역명 → 고유 숫자) ────────────────────────────────
export function strSeed(s: string): number {
  return s.split('').reduce((acc, c) => acc + c.charCodeAt(0), 0);
}
