export function seededPick<T>(seed: number, variants: T[]): T {
  // LCG: 간단하고 빠른 시드 기반 선택
  const s = ((seed * 1664525 + 1013904223) >>> 0) % variants.length;
  return variants[s];
}

// 시드를 조금씩 다르게 써서 여러 번 뽑을 때 다양성 확보
export function seededPickN<T>(seed: number, variants: T[], n: number): T[] {
  const result: T[] = [];
  const used = new Set<number>();
  for (let i = 0; i < n && result.length < variants.length; i++) {
    const idx = ((seed * (i + 7) * 1664525 + 1013904223) >>> 0) % variants.length;
    // 충돌 시 선형 탐색
    let j = idx;
    while (used.has(j)) j = (j + 1) % variants.length;
    used.add(j);
    result.push(variants[j]);
  }
  return result;
}

